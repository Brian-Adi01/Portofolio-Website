const LANG_KEY = 'lang';
function getLang() {
  try { const s = localStorage.getItem(LANG_KEY); if (s === 'en' || s === 'id') return s; } catch (e) {}
  return (navigator.language || '').toLowerCase().startsWith('id') ? 'id' : 'en';
}
function t(k) { return (I18N[window.LANG] && I18N[window.LANG][k]) || I18N.en[k] || k; }
function setLang(l, save) {
  window.LANG = l;
  document.documentElement.lang = l;
  if (save) { try { localStorage.setItem(LANG_KEY, l); } catch (e) {} }
  document.querySelectorAll('[data-i18n]').forEach(e => { e.textContent = t(e.dataset.i18n); });
  document.querySelectorAll('[data-i18n-alt]').forEach(e => { e.alt = t(e.dataset.i18nAlt); });
  document.querySelectorAll('[data-cv]').forEach(a => { a.href = 'assets/cv/CV-Gede-Brian-Adi-Mahendra-' + l.toUpperCase() + '.pdf'; }); // CV file follows the selected language
  document.querySelectorAll('[data-lang]').forEach(b => b.setAttribute('aria-pressed', b.dataset.lang === l));
  const tk = document.body.dataset.title;
  if (tk) document.title = t(tk) + ' | Gede Brian Adi Mahendra';
}
document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('[data-lang]').forEach(b => b.addEventListener('click', () => setLang(b.dataset.lang, true)));
  setLang(getLang(), false);
});

